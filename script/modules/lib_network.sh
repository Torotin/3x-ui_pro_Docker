#!/usr/bin/env bash
# Shared host network helpers (path MTU, default iface).

network_default_iface() {
	ip -4 route show default 2>/dev/null | awk '{
		for (i = 1; i <= NF; i++) {
			if ($i == "dev") {
				print $(i + 1)
				exit
			}
		}
	}'
}

network_iface_mtu() {
	local iface=${1:-}
	[[ -n "$iface" ]] || return 1
	cat "/sys/class/net/${iface}/mtu" 2>/dev/null
}

# Print iface:path_mtu. Uses IPv4 DF ping binary search when current MTU blackholes.
network_detect_path_mtu() {
	local target=${1:-1.1.1.1}
	local iface current_mtu lo=1280 hi mid best=1280 payload
	if [[ "${INSTALL_MOCK:-0}" == "1" ]]; then
		printf '%s\n' "${INSTALL_MOCK_PATH_MTU:-eth0:1500}"
		return 0
	fi
	iface=$(network_default_iface)
	[[ -n "$iface" ]] || return 1
	current_mtu=$(network_iface_mtu "$iface" || echo 1500)
	[[ "$current_mtu" =~ ^[0-9]+$ ]] || current_mtu=1500
	hi=$current_mtu
	payload=$((hi - 28))
	((payload < 64)) && payload=64
	if ping -4 -M do -s "$payload" -c 1 -W 1 "$target" >/dev/null 2>&1; then
		printf '%s:%s\n' "$iface" "$hi"
		return 0
	fi
	best=1280
	while ((lo <= hi)); do
		mid=$(((lo + hi) / 2))
		payload=$((mid - 28))
		((payload < 64)) && payload=64
		if ping -4 -M do -s "$payload" -c 1 -W 1 "$target" >/dev/null 2>&1; then
			best=$mid
			lo=$((mid + 1))
		else
			hi=$((mid - 1))
		fi
	done
	printf '%s:%s\n' "$iface" "$best"
}

# Lower iface MTU when path MTU is smaller; enable tcp_mtu_probing; optional netplan persist.
# Opt out: INSTALL_NETWORK_FIX_MTU=0.
install_network_fix_path_mtu() {
	local detected iface path_mtu current_mtu
	local target=${INSTALL_NETWORK_MTU_PROBE_TARGET:-1.1.1.1}
	[[ "${INSTALL_NETWORK_FIX_MTU:-1}" == "1" ]] || return 0

	if [[ "${INSTALL_MOCK:-0}" == "1" ]]; then
		detected=$(network_detect_path_mtu "$target")
		run_cmd network.mtu.detect printf '%s\n' "$detected"
		iface=${detected%%:*}
		path_mtu=${detected##*:}
		current_mtu=${INSTALL_MOCK_IFACE_MTU:-1500}
		if ((path_mtu < current_mtu)); then
			run_cmd network.mtu.apply ip link set dev "$iface" mtu "$path_mtu"
			run_cmd network.mtu.sysctl sysctl -w net.ipv4.tcp_mtu_probing=2
			run_cmd network.mtu.netplan printf 'netplan mtu %s on %s\n' "$path_mtu" "$iface"
		fi
		return 0
	fi

	detected=$(network_detect_path_mtu "$target") || {
		log WARN "path MTU probe failed; leaving interface MTU unchanged"
		return 0
	}
	iface=${detected%%:*}
	path_mtu=${detected##*:}
	[[ -n "$iface" && "$path_mtu" =~ ^[0-9]+$ ]] || return 0
	current_mtu=$(network_iface_mtu "$iface" || echo 1500)
	[[ "$current_mtu" =~ ^[0-9]+$ ]] || current_mtu=1500

	run_cmd network.mtu.detect printf '%s (iface mtu %s)\n' "$detected" "$current_mtu"
	# Active Path MTU probing (2) for overlay/cloud MTU during installs/pulls.
	run_cmd network.mtu.sysctl sysctl -w net.ipv4.tcp_mtu_probing=2 || true

	if ((path_mtu >= current_mtu)); then
		printf 'Path MTU OK: %s mtu %s\n' "$iface" "$current_mtu"
		return 0
	fi

	printf 'Path MTU clamp: %s %s -> %s\n' "$iface" "$current_mtu" "$path_mtu"
	run_cmd network.mtu.apply ip link set dev "$iface" mtu "$path_mtu" || {
		log WARN "failed to set $iface mtu $path_mtu"
		return 0
	}
	install_network_persist_mtu_netplan "$iface" "$path_mtu" || true
}

# Write /etc/netplan/99-3xui-mtu.yaml when netplan is in use. Does not disable cloud-init.
install_network_persist_mtu_netplan() {
	local iface=$1 mtu=$2
	local netplan_dir=/etc/netplan
	local out="$netplan_dir/99-3xui-mtu.yaml"
	[[ "${INSTALL_NETWORK_PERSIST_MTU:-1}" == "1" ]] || return 0
	[[ -d "$netplan_dir" ]] || return 0
	compgen -G "$netplan_dir/*.yaml" >/dev/null 2>&1 || compgen -G "$netplan_dir/*.yml" >/dev/null 2>&1 || return 0

	backup_file "$out" 2>/dev/null || true
	cat >"$out" <<YAML
# Generated by 3x-ui installer — path MTU clamp for overlay/cloud NICs.
network:
  version: 2
  ethernets:
    ${iface}:
      mtu: ${mtu}
YAML
	chmod 0600 "$out"
	run_cmd network.mtu.netplan printf 'wrote %s (mtu %s)\n' "$out" "$mtu"
	if command -v netplan >/dev/null 2>&1; then
		run_cmd network.mtu.netplan.apply netplan apply || log WARN "netplan apply failed after MTU drop-in"
	fi
}
