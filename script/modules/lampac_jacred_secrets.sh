# shellcheck shell=bash
# Apply LAMPAC_JACRED_APIKEY into live Lampac init.conf + client inject JS.

apply_lampac_jacred_secrets() {
	local key=${LAMPAC_JACRED_APIKEY:-}
	local initf="$INSTALL_ROOT/lampac/config/init.conf"
	local override_dir="$INSTALL_ROOT/lampac/plugins/override"
	local inject="$override_dir/jacred-apikey.local.js"

	if [[ -z "$key" ]]; then
		die "LAMPAC_JACRED_APIKEY is empty; refuse to apply JacRed secrets"
	fi
	if [[ ! -f "$initf" ]]; then
		die "Lampac init.conf missing: $initf"
	fi

	mkdir -p "$override_dir"
	if [[ -d "$inject" ]]; then
		rm -rf -- "$inject"
	fi
	backup_file "$initf"

	python3 - "$initf" "$key" "$inject" <<'PY'
import json, pathlib, sys
init_path = pathlib.Path(sys.argv[1])
secret = sys.argv[2]
inject_path = pathlib.Path(sys.argv[3])
data = json.loads(init_path.read_text(encoding="utf-8"))
jac = data.setdefault("JacRed", {})
if not isinstance(jac, dict):
    raise SystemExit("JacRed must be a JSON object")
jac["apikey"] = secret
init_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
# JS string escape: hex key is safe; still quote via json
key_js = json.dumps(secret)
inject_path.write_text(
    "// Generated by apply_lampac_jacred_secrets — do not commit\n"
    f"window.__lampac_jacred_apikey = {key_js};\n"
    "try {\n"
    f"  localStorage.setItem('jackett_key', {key_js});\n"
    "  localStorage.setItem('parser_torrent_type', 'jackett');\n"
    "  localStorage.setItem('parser_use', 'true');\n"
    "} catch (e) {}\n",
    encoding="utf-8",
)
PY
}
